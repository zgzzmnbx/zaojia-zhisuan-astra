import {readFile,writeFile,mkdir,copyFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=path.dirname(fileURLToPath(import.meta.url));
const backup=path.join(root,'backups','before-pale-river');
await mkdir(backup,{recursive:true});
for(const name of ['white-sandbox.glb','white-sandbox.blend','white-sandbox-flow.blend','白模空间-独立预览.html','preview-information-flow.png','information-flow.mp4','README.md','delivery-manifest.json'])await copyFile(path.join(root,name),path.join(backup,name),1).catch(error=>{if(error.code!=='EEXIST')throw error});
const file=path.join(root,'white-sandbox.glb'),buffer=await readFile(file);
if(buffer.toString('ascii',0,4)!=='glTF')throw new Error('Not a GLB');
const jsonLength=buffer.readUInt32LE(12);
const doc=JSON.parse(buffer.toString('utf8',20,20+jsonLength));
const river=doc.materials.find(m=>m.name==='Blue river');
if(!river)throw new Error('Missing river material');
river.pbrMetallicRoughness.baseColorFactor=[.12,.42,.72,1];
river.pbrMetallicRoughness.roughnessFactor=.68;
river.pbrMetallicRoughness.metallicFactor=0;
const json=Buffer.from(JSON.stringify(doc)),padded=Buffer.alloc(Math.ceil(json.length/4)*4,0x20);json.copy(padded);
const rest=buffer.subarray(20+jsonLength),header=Buffer.from(buffer.subarray(0,20));
header.writeUInt32LE(20+padded.length+rest.length,8);header.writeUInt32LE(padded.length,12);
await writeFile(file,Buffer.concat([header,padded,rest]));
console.log('Updated river only:',river.pbrMetallicRoughness);
