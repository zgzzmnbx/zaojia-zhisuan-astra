async (page) => {
  await page.getByRole('switch',{name:'信息流',exact:true}).uncheck();
  const checks=[];
  const state=()=>page.evaluate(()=>window.__whiteSandbox.getState());
  const assert=(ok,name)=>{if(!ok)throw new Error(name);checks.push(name)};
  const settle=()=>page.waitForFunction(()=>!window.__whiteSandbox.getState().framePending,null,{timeout:10000});
  const route=async (id,title)=>{await page.locator('#all-toggle').click();await page.locator('#all-menu button').filter({hasText:title}).click();await page.waitForFunction(id=>window.__whiteSandbox.getState().active===id,id);await settle()};
  await settle();assert((await state()).ready,'真实 GLB 已在 WebGL 中加载');
  assert(await page.locator('.hotspot').count()===7,'七个建筑入口齐全');
  assert((await state()).shadows&&await page.getByRole('switch',{name:'场景阴影'}).isChecked(),'场景阴影默认开启');
  const glass=await page.locator('.float-panel').evaluateAll(els=>els.filter(el=>!el.hidden).map(el=>{const c=getComputedStyle(el);return {id:el.id||el.className,filter:c.backdropFilter,background:c.backgroundColor}}));
  assert(glass.every(g=>g.filter.includes('blur(22px)')&&g.background.includes('0.5')),'可见聊天窗与工具栏使用真实半透明背景及毛玻璃滤镜');
  const draft='这份草稿在切换视图后必须保留';
  await page.getByRole('textbox',{name:'向智算提问'}).fill(draft);
  await page.getByRole('button',{name:'进入风险复核',exact:true}).click();await settle();
  assert((await state()).active==='risk','风险建筑入口与镜头联动');
  assert((await state()).draft===draft,'推近镜头后草稿保留');
  const shadowBefore=await state();
  await page.mouse.move(10,80);
  const shadowOn=await page.screenshot({clip:{x:430,y:350,width:700,height:430}});
  await page.getByRole('switch',{name:'场景阴影'}).uncheck();await page.mouse.move(10,80);await settle();
  const shadowOff=await page.screenshot({clip:{x:430,y:350,width:700,height:430}});
  assert(!(await state()).shadowMap&&!(await state()).shadows&&!(await state()).bloom.contactShadows,'关闭开关后投影和接触阴影同时禁用');
  assert(!shadowOn.equals(shadowOff),'相同视角下建筑和地面的实际渲染随阴影开关变化');
  assert((await state()).draft===draft&&(await state()).active==='risk'&&(await state()).camera.every((v,i)=>Math.abs(v-shadowBefore.camera[i])<.0001),'阴影切换保留功能、草稿与镜头');
  await page.getByRole('switch',{name:'场景阴影'}).focus();await page.keyboard.press('Space');await settle();
  assert((await state()).shadowMap&&(await state()).bloom.contactShadows&&await page.getByRole('switch',{name:'场景阴影'}).isChecked(),'阴影开关支持键盘恢复');
  await page.mouse.move(10,80);
  const shadowRestored=await page.screenshot({clip:{x:430,y:350,width:700,height:430}});
  assert(shadowOn.equals(shadowRestored),'重新开启阴影恢复原始渲染');
  await page.locator('#enter-demo').click();assert(await page.locator('.table-preview').isVisible(),'功能浮层打开操作示例');
  await page.keyboard.press('Escape');await settle();assert((await state()).active===null,'Escape 返回全景');
  assert((await state()).draft===draft,'返回全景后草稿保留');
  await page.getByRole('button',{name:'收起聊天'}).click();assert(!(await state()).chatOpen,'聊天可以收起');
  await page.getByRole('button',{name:'展开聊天'}).click();assert((await state()).draft===draft,'重新展开聊天后草稿保留');
  for(const [id,title] of [['import','清单导入'],['price','智能填价'],['knowledge','知识检索'],['report','报告生成'],['review','协同复核'],['table','专业表格']]){
    await route(id,title);assert((await state()).active===id,title+'等效菜单入口');
    await page.locator('#enter-demo').click();assert(await page.locator('.example-label').first().isVisible(),title+'示例状态明确');
    await page.keyboard.press('Escape');await settle();
  }
  const p=await page.evaluate(()=>window.__whiteSandbox.projectZone('report'));
  await page.mouse.click(p.x,p.y);await settle();assert((await state()).active==='report','实际三维建筑网格可点选');
  await page.keyboard.press('Escape');await settle();
  const before=(await state()).camera;
  await page.mouse.move(1220,770);await page.mouse.down();await page.mouse.move(1320,730,{steps:10});await page.mouse.up();await settle();
  const after=(await state()).camera;assert(Math.hypot(...after.map((v,i)=>v-before[i]))>1,'鼠标拖动实际改变镜头');
  const distance=s=>Math.hypot(...s.camera.map((v,i)=>v-s.target[i]));const d0=distance(await state());
  await page.mouse.wheel(0,-200);await settle();assert(distance(await state())<d0,'滚轮实际缩放');
  await page.locator('#reset').click();await settle();await page.locator('#orbit').click();
  const orbit0=(await state()).camera;await page.waitForTimeout(400);const orbit1=(await state()).camera;
  assert(Math.hypot(...orbit1.map((v,i)=>v-orbit0[i]))>.01,'手动开启环游后镜头持续推进');
  await page.locator('#orbit').click();await settle();assert(!(await state()).auto,'环游可暂停且停止逐帧渲染');
  await page.emulateMedia({reducedMotion:'reduce'});await route('table','专业表格');
  assert((await state()).target.every((v,i)=>Math.abs(v-[-7.7,4.8,-9.1][i])<.001),'减少动效时直接定位目标');
  await page.setViewportSize({width:1366,height:900});await settle();
  const fits=await page.locator('#inspector').evaluate(el=>{const r=el.getBoundingClientRect();return r.left>=0&&r.right<=innerWidth&&r.bottom<=innerHeight});assert(fits,'1366 桌面功能浮层完整可见');
  await page.setViewportSize({width:1600,height:1000});await page.keyboard.press('Escape');await settle();
  await page.getByRole('textbox',{name:'向智算提问'}).fill('');await page.emulateMedia({reducedMotion:'no-preference'});
  await page.screenshot({path:'05-视觉识别/02-3D场景/white-sandbox-v0.1.0/preview-overview.png'});
  await page.getByRole('switch',{name:'场景阴影'}).uncheck();await settle();await page.mouse.move(10,80);
  await page.screenshot({path:'05-视觉识别/02-3D场景/white-sandbox-v0.1.0/preview-shadows-off.png'});
  await page.getByRole('switch',{name:'场景阴影'}).check();await settle();await page.mouse.move(10,80);
  await route('risk','风险复核');await page.screenshot({path:'05-视觉识别/02-3D场景/white-sandbox-v0.1.0/preview-risk.png'});
  await page.keyboard.press('Escape');await settle();await route('table','专业表格');
  await page.locator('#enter-demo').click();await page.screenshot({path:'05-视觉识别/02-3D场景/white-sandbox-v0.1.0/preview-table.png'});
  await page.keyboard.press('Escape');await settle();
  return {checks,assertionCount:checks.length,state:await state(),glass,viewport:{width:1600,height:1000}};
}
