import {build} from 'vite';
import tailwind from '@tailwindcss/vite';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=path.dirname(fileURLToPath(import.meta.url));
const model=(await readFile(path.join(root,'white-sandbox.glb'))).toString('base64');
await build({root,configFile:false,base:'./',plugins:[tailwind()],define:{__MODEL_B64__:JSON.stringify(model)},build:{outDir:path.join(root,'preview-build'),emptyOutDir:false,assetsInlineLimit:10000000,cssCodeSplit:false,reportCompressedSize:false,rollupOptions:{output:{inlineDynamicImports:true}}}});
const dist=path.join(root,'preview-build');let html=await readFile(path.join(dist,'index.html'),'utf8');
const script=html.match(/<script[^>]+src="([^"]+)"[^>]*><\/script>/);
const style=html.match(/<link[^>]+href="([^"]+\.css)"[^>]*>/);
if(!script||!style)throw new Error('Missing bundled output');
const js=await readFile(path.join(dist,script[1]),'utf8');const css=await readFile(path.join(dist,style[1]),'utf8');
html=html.replace(script[0],()=>'<script type="module">'+js.replace(/<\/script/gi,'<\\/script')+'</script>').replace(style[0],()=>'<style>'+css+'</style>');
await writeFile(path.join(root,'白模空间-独立预览.html'),html,'utf8');
await writeFile(path.join(root,'browser-load.js'),'async (page) => { await page.goto("about:blank"); await page.setViewportSize({width:1600,height:1000}); await page.setContent('+JSON.stringify(html)+', {waitUntil:"load"}); await page.waitForFunction(() => document.body.dataset.ready === "true", {timeout:30000}); console.log(JSON.stringify(await page.evaluate(() => window.__whiteSandbox.getState()))); }','utf8');
console.log('STANDALONE_READY',path.join(root,'白模空间-独立预览.html'));
