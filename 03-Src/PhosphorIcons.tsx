import {forwardRef,type SVGProps} from 'react';
import {glyphs} from './vendor/phosphor-duotone/glyphs.js';

type IconProps=Omit<SVGProps<SVGSVGElement>,'children'|'dangerouslySetInnerHTML'> & {size?:number|string;absoluteStrokeWidth?:boolean;title?:string};
function createIcon(name:keyof typeof glyphs){
 const Component=forwardRef<SVGSVGElement,IconProps>(function PhosphorIcon({size=24,color='currentColor',className='',style,strokeWidth:_strokeWidth,absoluteStrokeWidth:_absoluteStrokeWidth,title,...props},ref){
  const named=!!(title||props['aria-label']||props['aria-labelledby']);
  return <svg ref={ref} width={size} height={size} color={color} aria-hidden={named?undefined:true} role={named?'img':undefined} focusable="false" {...props} className={`astra-phosphor ${className}`} data-phosphor={name} viewBox="0 0 256 256" fill="currentColor" stroke="none" style={{...style,fill:'currentColor',stroke:'none'}}>{title&&<title>{title}</title>}<g dangerouslySetInnerHTML={{__html:glyphs[name]}}/></svg>;
 });
 Component.displayName=`Phosphor(${name})`;
 return Component;
}
